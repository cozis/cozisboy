#!/usr/bin/env python3
"""Extract the launcher's 5x7 pixel font (apps/ui/gfx.c, FONT[96][7]) into a
JS module for the web app: apps/web/mock/font5x7.js (and later the real page).
Each glyph is 7 rows, 5 bits per row, MSB = leftmost pixel."""
import re, sys, json, pathlib

top = pathlib.Path(__file__).resolve().parent.parent
src = (top / "apps/ui/gfx.c").read_text()
body = src[src.index("FONT[96][7] = {"):]
body = body[:body.index("\n};")]
glyphs = {}
for m in re.finditer(r"\['((?:\\.|[^'\\]))' - 32\]\s*=\s*\{([^}]*)\}", body):
    ch = m.group(1)
    ch = {"\\\\": "\\", "\\'": "'"}.get(ch, ch)
    rows = [int(x, 0) for x in m.group(2).split(",") if x.strip()]
    glyphs[ch] = rows + [0] * (7 - len(rows))
out = top / (sys.argv[1] if len(sys.argv) > 1 else "apps/web/mock/font5x7.js")
out.write_text("// Generated by tools/gen-webfont.py from apps/ui/gfx.c: do not edit.\n"
               "// 5x7 glyphs: 7 rows, 5 bits each, MSB = leftmost pixel.\n"
               f"const FONT5X7 = {json.dumps(glyphs, separators=(',', ':'))};\n")
print(f"{len(glyphs)} glyphs -> {out.relative_to(top)}")
