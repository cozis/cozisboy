static const uint8_t *glyph(char ch)
{
	if (ch < 32 || ch >= 127)
		ch = '?';
	return FONT[ch - 32];
}

int text_width(const char *s, int scale)
{
	int n = (int)strlen(s);
	return n ? n * 6 * scale - scale : 0;
}

// Draw every lit pixel of s, grown by `grow` and offset by (dx, dy).
static void text_pass(canvas *c, int x, int y, const char *s, int scale,
		      int grow, uint32_t col)
{
	for (; *s; s++, x += 6 * scale) {
		const uint8_t *g = glyph(*s);
		for (int r = 0; r < 7; r++)
			for (int k = 0; k < 5; k++)
				if (g[r] & (0x10 >> k))
					fill(c, x + k * scale - grow, y + r * scale - grow,
					     scale + 2 * grow, scale + 2 * grow, col);
	}
}

void text(canvas *c, int x, int y, const char *s, int scale, uint32_t col)
{
	text_pass(c, x, y, s, scale, 0, col);
}

void text_arcade(canvas *c, int x, int y, const char *s, int scale, uint32_t col)
{
	int o = scale >= 4 ? 2 : 1;        // white outline
	int ring = scale >= 4 ? 2 : 1;     // black ring
	int sh = scale >= 4 ? 4 : 2;       // shadow offset
	text_pass(c, x + sh, y + sh, s, scale, o + ring, BLACK);
	text_pass(c, x, y, s, scale, o + ring, BLACK);
	text_pass(c, x, y, s, scale, o, WHITE);
	text_pass(c, x, y, s, scale, 0, col);
}

void icon_from_rows(icon_t *ic, const char *const *rows, int n)
{
	ic->n = n;
	memset(ic->cell, '.', sizeof ic->cell);
	for (int y = 0; y < n && rows[y]; y++)
		for (int x = 0; x < n && rows[y][x]; x++)
			ic->cell[y][x] = rows[y][x];
}

static uint32_t icon_col(char ch, uint32_t main, uint32_t detail)
{
	switch (ch) {
	case '#': return main;
	case 'k': return detail;
	case 'a': return mix(detail, WHITE, 0.55f);
	case 'w': return WHITE;
	case 'l': return 0xc8c8d4;
	case 'g': return 0x8a8a9a;
	case 'd': return 0x2a2a36;
	case 'r': return 0xff4a4a;
	case 'y': return 0xffd93d;
	case 'n': return 0x5ee05e;
	case 'c': return 0x3fc8ff;
	case 'b': return 0x6a7dff;
	case 'p': return 0xff6bc1;
	case 'v': return 0xc56bff;
	}
	return main;
}

static void icon_pass(canvas *c, const icon_t *ic, int x, int y, int s, int grow, uint32_t col)
{
	for (int r = 0; r < ic->n; r++)
		for (int k = 0; k < ic->n; k++)
			if (ic->cell[r][k] != '.')
				fill(c, x + k * s - grow, y + r * s - grow, s + 2 * grow, s + 2 * grow, col);
}

void draw_icon_dim(canvas *c, const icon_t *ic, int x, int y, int scale, uint32_t main,
		   uint32_t detail, uint32_t shadow, float dim, uint32_t to)
{
	int o = scale >= 4 ? 2 : 1;
	icon_pass(c, ic, x + scale, y + scale, scale, o, shadow);
	icon_pass(c, ic, x, y, scale, o, BLACK);
	for (int r = 0; r < ic->n; r++)
		for (int k = 0; k < ic->n; k++) {
			char ch = ic->cell[r][k];
			if (ch == '.')
				continue;
			uint32_t col = icon_col(ch, main, detail);
			if (dim > 0 && ch != '#' && ch != 'k')
				col = mix(col, to, dim);
			fill(c, x + k * scale, y + r * scale, scale, scale, col);
		}
}

void draw_icon(canvas *c, const icon_t *ic, int x, int y, int scale,
	       uint32_t main, uint32_t detail, uint32_t shadow)
{
	draw_icon_dim(c, ic, x, y, scale, main, detail, shadow, 0, 0);
}
