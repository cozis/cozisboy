void fill(canvas *c, int x, int y, int w, int h, uint32_t col)
{
	int x0 = x < 0 ? 0 : x, y0 = y < 0 ? 0 : y;
	int x1 = x + w > c->w ? c->w : x + w, y1 = y + h > c->h ? c->h : y + h;
	for (int yy = y0; yy < y1; yy++) {
		uint32_t *row = c->px + (size_t)yy * c->stride;
		for (int xx = x0; xx < x1; xx++)
			row[xx] = col;
	}
}

void disc(canvas *c, int cx, int cy, int r, uint32_t col)
{
	for (int dy = -r; dy < r; dy++) {
		float fy = dy + 0.5f;
		int hw = (int)(sqrtf((float)(r * r) - fy * fy) + 0.5f);
		fill(c, cx - hw, cy + dy, 2 * hw, 1, col);
	}
}

void rrect(canvas *c, int x, int y, int w, int h, int r, uint32_t col)
{
	fill(c, x + r, y, w - 2 * r, h, col);
	fill(c, x, y + r, w, h - 2 * r, col);
}

void darken(canvas *c, int x, int y, int w, int h, float amount)
{
	int x0 = x < 0 ? 0 : x, y0 = y < 0 ? 0 : y;
	int x1 = x + w > c->w ? c->w : x + w, y1 = y + h > c->h ? c->h : y + h;
	unsigned k = (unsigned)((1 - amount) * 256);
	for (int yy = y0; yy < y1; yy++) {
		uint32_t *row = c->px + (size_t)yy * c->stride;
		for (int xx = x0; xx < x1; xx++) {
			uint32_t p = row[xx];
			row[xx] = ((((p >> 16) & 255) * k >> 8) << 16) |
				  ((((p >> 8) & 255) * k >> 8) << 8) | ((p & 255) * k >> 8);
		}
	}
}

uint32_t mix(uint32_t a, uint32_t b, float t)
{
	if (t <= 0)
		return a;
	if (t >= 1)
		return b;
	int ar = (a >> 16) & 255, ag = (a >> 8) & 255, ab = a & 255;
	int br = (b >> 16) & 255, bg = (b >> 8) & 255, bb = b & 255;
	return (uint32_t)((ar + (int)((br - ar) * t)) << 16 |
			  (ag + (int)((bg - ag) * t)) << 8 |
			  (ab + (int)((bb - ab) * t)));
}

